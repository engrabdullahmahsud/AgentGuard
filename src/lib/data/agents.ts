export function getAgentById(id: string): Agent | undefined {
  return agents.find(a => a.id === id);
}

export function getHighRiskAgents(): Agent[] {
  return agents.filter(a => a.risk === 'high');
}

export function getAgentsByRisk(risk: string): Agent[] {
  return agents.filter(a => a.risk === risk);
}

export function getRiskDistribution() {
  return {
    low: agents.filter(a => a.risk === 'low').length,
    medium: agents.filter(a => a.risk === 'medium').length,
    high: agents.filter(a => a.risk === 'high').length,
  };
}
